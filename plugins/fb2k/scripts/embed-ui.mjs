// Writes src/fb2k/ui_assets_table.cpp: every file of Jean's build under ui/dist, and under api/
// the contract and the Swagger UI page that renders it, as a byte array each and one table of
// their paths and bytes, the same source for every platform's build.
//
//   pnpm --dir ui build && node plugins/fb2k/scripts/embed-ui.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const fb2kRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = dirname(dirname(fb2kRoot));
const dist = join(repo, "ui", "dist");
const contract = join(repo, "contract");
const output = join(fb2kRoot, "src", "fb2k", "ui_assets_table.cpp");

const swaggerUiFiles = ["swagger-ui.css", "swagger-ui-bundle.js"];

const bytesPerLine = 32;

function fail(message) {
	console.error(`embed-ui: ${message}`);
	process.exit(1);
}

function filesUnder(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) return filesUnder(path);
		return entry.isFile() ? [path] : [];
	});
}

const embeddedPath = (root, full) => relative(root, full).split(sep).join("/");

function jeanBuild() {
	let paths;
	try {
		paths = filesUnder(dist);
	} catch {
		fail(`no Jean build at ${dist} -- run 'pnpm --dir ui build' first.`);
	}
	if (paths.length === 0)
		fail(`${dist} holds no files -- run 'pnpm --dir ui build' first.`);

	return paths.map((full) => ({ path: embeddedPath(dist, full), full }));
}

function apiDocs() {
	const docs = join(contract, "docs");
	const page = filesUnder(docs).map((full) => ({
		path: `api/docs/${embeddedPath(docs, full)}`,
		full,
	}));

	const resolve = createRequire(join(contract, "package.json")).resolve;
	let swaggerUi;
	try {
		swaggerUi = swaggerUiFiles.map((name) => ({
			path: `api/docs/${name}`,
			full: resolve(`swagger-ui-dist/${name}`),
		}));
	} catch {
		fail("swagger-ui-dist is not installed -- run 'pnpm install' first.");
	}

	return [
		{ path: "api/openapi.yaml", full: join(contract, "openapi.yaml") },
		...page,
		...swaggerUi,
	];
}

// Every byte outside printable ASCII, and the two that end or escape a literal, as a three-digit
// octal escape, which cannot swallow a character that follows it.
function literal(text) {
	const escaped = [...Buffer.from(text, "utf8")].map((byte) =>
		byte < 0x20 || byte > 0x7e || byte === 0x22 || byte === 0x5c
			? `\\${byte.toString(8).padStart(3, "0")}`
			: String.fromCharCode(byte),
	);
	return `"${escaped.join("")}"`;
}

// Numbers rather than a string literal, which MSVC refuses past about 64 KiB (C2026). Signed, so
// that every value fits a char and no compiler warns of a narrowing.
function arrayBody(bytes) {
	const lines = [];
	for (let at = 0; at < bytes.length; at += bytesPerLine) {
		const row = [];
		for (const byte of bytes.subarray(at, at + bytesPerLine))
			row.push(byte > 127 ? byte - 256 : byte);
		lines.push(`${row.join(",")},`);
	}
	return lines.join("\n");
}

const files = [...jeanBuild(), ...apiDocs()].sort((a, b) =>
	Buffer.compare(Buffer.from(a.path, "utf8"), Buffer.from(b.path, "utf8")),
);

const out = [
	"// Generated by scripts/embed-ui.mjs from ui/dist and contract/. Do not edit by hand.",
	'#include "fb2k/PCH.h"',
	"",
	'#include "core/assets.h"',
	'#include "fb2k/ui_assets.h"',
	"",
	"#include <span>",
	"#include <string_view>",
	"",
	"namespace jean {",
	"namespace generated {",
	"namespace {",
	"",
];

const rows = [];
files.forEach((file, index) => {
	const bytes = readFileSync(file.full);
	const name = `kFile${index}`;
	// A zero-length array is ill-formed, so an empty file gets one byte the view never reaches.
	out.push(
		`constexpr char ${name}[] = {`,
		bytes.length === 0 ? "0," : arrayBody(bytes),
		"};",
		"",
	);
	rows.push(
		`    {${literal(file.path)}, std::string_view(${name}, ${bytes.length})},`,
	);
});

out.push(
	"constexpr EmbeddedFile kFiles[] = {",
	...rows,
	"};",
	"",
	"}  // namespace",
	"",
	"std::span<const EmbeddedFile> embeddedUiFiles() {",
	"    return kFiles;",
	"}",
	"",
	"}  // namespace generated",
	"}  // namespace jean",
	"",
);

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, out.join("\n"));
process.stdout.write(
	`embed-ui: wrote ${output} for ${files.length} files under ${dist} and ${contract}\n`,
);
