# Ids rather than names: Windows resource names are case-insensitive and Vite hashes a file's
# name in mixed case, so two files could collide under a name-keyed lookup. FindResourceW is
# asked for an integer id instead, against the "JEANASSET" type, which is its own namespace and
# so never collides with the dialog ids in resource.h.
$ErrorActionPreference = 'Stop'
$fb2kRoot = Split-Path -Parent $PSScriptRoot
$repoRoot = Split-Path -Parent (Split-Path -Parent $fb2kRoot)
$dist = Join-Path $repoRoot 'ui\dist'

if (-not (Test-Path $dist)) {
  throw "No Jean build at $dist -- run 'pnpm --dir ui build' first."
}

$distFull = (Resolve-Path $dist).Path
$files = Get-ChildItem -Path $distFull -Recurse -File | Sort-Object { $_.FullName }
if ($files.Count -eq 0) {
  throw "$distFull holds no files -- run 'pnpm --dir ui build' first."
}

$rootNames = Get-ChildItem -Path $distFull -Force | ForEach-Object { $_.Name } | Sort-Object

$resourceType = 'JEANASSET'

$rc = [System.Text.StringBuilder]::new()
[void]$rc.AppendLine('// Generated by scripts/embed-ui.ps1 from ui/dist. Do not edit by hand.')
[void]$rc.AppendLine()

$table = [System.Text.StringBuilder]::new()
[void]$table.AppendLine('// Generated by scripts/embed-ui.ps1 from ui/dist. Do not edit by hand.')
[void]$table.AppendLine('namespace jean {')
[void]$table.AppendLine('namespace generated {')
[void]$table.AppendLine()
[void]$table.AppendLine("constexpr const wchar_t* kUiAssetResourceType = L`"$resourceType`";")
[void]$table.AppendLine()
[void]$table.AppendLine('struct UiAssetEntry {')
[void]$table.AppendLine('    const char* path;')
[void]$table.AppendLine('    int id;')
[void]$table.AppendLine('};')
[void]$table.AppendLine()
[void]$table.AppendLine('constexpr UiAssetEntry kUiAssets[] = {')

# Relative to this .rc's own folder rather than absolute: rc.exe resolves a resource
# statement's filename against that folder (confirmed on the build machine), and a checkout
# under a non-ASCII path would otherwise break the ascii-encoded .rc below.
$rcDir = Join-Path $fb2kRoot 'src\fb2k'

$id = 1
foreach ($file in $files) {
  $relative = $file.FullName.Substring($distFull.Length + 1).Replace('\', '/')

  $fromUri = [Uri]("$rcDir\")
  $toUri = [Uri]$file.FullName
  $rcRelativeUri = $fromUri.MakeRelativeUri($toUri).ToString()
  $rcRelative = [Uri]::UnescapeDataString($rcRelativeUri).Replace('/', '\')
  $rcPath = $rcRelative.Replace('\', '\\').Replace('"', '\"')

  [void]$rc.AppendLine("$id $resourceType `"$rcPath`"")
  [void]$table.AppendLine("    {`"$relative`", $id},")
  $id++
}

[void]$table.AppendLine('};')
[void]$table.AppendLine()
[void]$table.AppendLine('constexpr const char* kUiRootNames[] = {')
foreach ($name in $rootNames) {
  [void]$table.AppendLine("    `"$name`",")
}
[void]$table.AppendLine('};')
[void]$table.AppendLine()
[void]$table.AppendLine('}  // namespace generated')
[void]$table.AppendLine('}  // namespace jean')

$rcOut = Join-Path $fb2kRoot 'src\fb2k\ui_assets.rc'
$tableOut = Join-Path $fb2kRoot 'src\fb2k\ui_assets_table.inc'

Set-Content -Path $rcOut -Value $rc.ToString() -Encoding ascii
Set-Content -Path $tableOut -Value $table.ToString() -Encoding ascii

Write-Output "Wrote $rcOut and $tableOut for $($files.Count) files under $distFull"
